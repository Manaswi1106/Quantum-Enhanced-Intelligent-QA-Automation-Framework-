"""AI Test Generation Orchestrator with Pydantic schema validation.
Strictly disallows any hardcoded fallback or predefined application mocks.
Dynamically builds focus batches based on actual discovered functional areas.
"""
import logging
import os
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from dotenv import load_dotenv
from pydantic import BaseModel, Field, field_validator
from .gemini_provider import GeminiProvider
from .openai_provider import OpenAIProvider
from .provider import AIProvider

logger = logging.getLogger(__name__)

# Ensure .env is loaded
env_path = Path(__file__).resolve().parent.parent.parent / ".env"
if env_path.exists():
    load_dotenv(dotenv_path=env_path)
else:
    load_dotenv()


class GeneratedTestCase(BaseModel):
    """Pydantic model for validating test cases generated by AI."""
    test_id: Optional[str] = Field(default=None, description="Optional raw test ID proposed by AI")
    name: str = Field(..., min_length=3, description="Descriptive test name")
    description: str = Field(..., description="Explanation of what is verified")
    priority: str = Field(default="medium", description="critical, high, medium, low")
    target_route: Optional[str] = Field(default="/", description="Route where test begins")
    steps: List[str] = Field(default_factory=list, description="Ordered test steps")
    expected_result: str = Field(..., description="Expected assertion outcome")
    risk: float = Field(default=0.5, ge=0.0, le=1.0, description="Risk weight")
    coverage: float = Field(default=0.5, ge=0.0, le=1.0, description="Functional coverage weight")
    execution_cost: float = Field(default=5.0, ge=0.5, le=60.0, description="Estimated duration in seconds")
    redundancy_group: Optional[str] = Field(default=None, description="Grouping identifier for overlap control")

    @field_validator("priority")
    @classmethod
    def validate_priority(cls, v: str) -> str:
        v_clean = v.lower().strip()
        if v_clean not in {"critical", "high", "medium", "low"}:
            return "medium"
        return v_clean


def get_active_ai_provider() -> Optional[AIProvider]:
    """Resolve configured AI provider based on environment variables."""
    preferred = os.getenv("AI_PROVIDER", "gemini").lower().strip()

    if preferred == "gemini":
        gemini = GeminiProvider()
        if gemini.is_configured():
            return gemini
        openai = OpenAIProvider()
        if openai.is_configured():
            return openai
    elif preferred == "openai":
        openai = OpenAIProvider()
        if openai.is_configured():
            return openai
        gemini = GeminiProvider()
        if gemini.is_configured():
            return gemini

    # Check either if not explicitly preferred
    gemini = GeminiProvider()
    if gemini.is_configured():
        return gemini
    openai = OpenAIProvider()
    if openai.is_configured():
        return openai

    return None


def get_all_configured_providers() -> List[AIProvider]:
    """Return all configured AI providers, ordered with preferred first."""
    preferred = os.getenv("AI_PROVIDER", "gemini").lower().strip()
    providers: List[AIProvider] = []
    
    gemini = GeminiProvider()
    openai = OpenAIProvider()
    
    if preferred == "openai":
        if openai.is_configured():
            providers.append(openai)
        if gemini.is_configured():
            providers.append(gemini)
    else:
        if gemini.is_configured():
            providers.append(gemini)
        if openai.is_configured():
            providers.append(openai)
            
    return providers


def get_ai_status() -> Dict[str, Any]:
    """Return status of AI provider configuration."""
    provider = get_active_ai_provider()
    if provider:
        return {
            "configured": True,
            "provider": provider.get_name(),
            "message": f"AI provider '{provider.get_name()}' is active and connected."
        }
    return {
        "configured": False,
        "provider": None,
        "message": "AI provider not configured. Set GEMINI_API_KEY or OPENAI_API_KEY in backend/.env."
    }


def generate_tests_from_context(app_context: Dict[str, Any]) -> Tuple[List[Dict[str, Any]], str, bool]:
    """Generate test cases from discovered application context via an actual AI provider.

    Returns:
        (test_cases, provider_name, is_ai)
    Raises:
        RuntimeError if no AI provider is configured or if generation fails across all providers.
    """
    configured_providers = get_all_configured_providers()

    if not configured_providers:
        logger.warning("No AI provider configured (GEMINI_API_KEY or OPENAI_API_KEY missing).")
        return [], "", False

    pages = app_context.get("pages", [])
    buttons = app_context.get("buttons", [])
    inputs = app_context.get("inputs", [])
    forms = app_context.get("forms", [])
    links = app_context.get("links", [])

    total_elements = len(buttons) + len(inputs) + len(forms)

    # Check which functional areas exist in discovered elements
    has_search = any(
        "search" in (inp.get("placeholder") or "").lower() or
        "search" in (inp.get("name") or "").lower() or
        "search" in (b.get("text") or "").lower()
        for inp in inputs for b in buttons
    )
    has_auth = any(
        inp.get("type") in ("password", "email") or
        "login" in (b.get("text") or "").lower() or
        "sign" in (b.get("text") or "").lower() or
        any("login" in str(p.get("path", "")).lower() for p in pages)
        for inp in inputs for b in buttons
    )
    has_actions = any(
        any(k in (b.get("text") or "").lower() for k in ["cart", "add", "buy", "submit", "order", "save", "delete"])
        for b in buttons
    )
    has_multi_pages = len(pages) > 2

    # Dynamically formulate generation batches
    batches = []

    if has_multi_pages or total_elements > 15:
        # Batch 1: Route Navigation, Page Loads & Header State
        batches.append({
            "focus_area": "Route Navigation, Page Load Verification, and View Transitions across discovered pages",
            "url": app_context.get("url"),
            "name": app_context.get("name"),
            "pages": pages[:25],
            "buttons": [b for b in buttons if b.get("type") == "link" or b.get("page") == "/"][:20] or buttons[:15],
            "inputs": [],
            "forms": [],
            "links": links[:25],
        })

        # Batch 2: Interactive Actions, Buttons & Commerce / Workflows (if present)
        if has_actions or len(buttons) > 5:
            action_buttons = [
                b for b in buttons
                if any(k in (b.get("text") or "").lower() for k in ["cart", "add", "buy", "order", "view", "open", "shop"])
            ] or buttons[:35]
            batches.append({
                "focus_area": "Interactive Action Buttons, State Changes, and Primary User Workflows",
                "url": app_context.get("url"),
                "name": app_context.get("name"),
                "pages": pages[:15],
                "buttons": action_buttons[:40],
                "inputs": inputs[:15],
                "forms": forms[:5],
                "links": links[:15],
            })

        # Batch 3: Forms, Search, Inputs & Validation / Edge Cases (if present)
        if len(inputs) > 0 or len(forms) > 0 or has_search or has_auth:
            batches.append({
                "focus_area": "Form Submissions, Search/Filter Inputs, Data Entry, and Input Validation Scenarios",
                "url": app_context.get("url"),
                "name": app_context.get("name"),
                "pages": [p for p in pages if p.get("inputs_count", 0) > 0 or p.get("forms_count", 0) > 0][:10] or pages[:10],
                "buttons": [b for b in buttons if any(k in (b.get("text") or "").lower() for k in ["search", "submit", "login", "filter"])] or buttons[:15],
                "inputs": inputs[:30],
                "forms": forms[:15],
                "links": [],
            })
    else:
        # Single cohesive batch for minimal or single-page contexts
        batches.append(dict(app_context))

    logger.info(f"Formulated {len(batches)} dynamic AI focus batches based on discovered functionality.")

    # Try providers in order
    last_error = None
    for provider in configured_providers:
        logger.info(
            f"AI Test Generation requested via '{provider.get_name()}'. "
            f"Discovered Context: {len(pages)} pages, {len(buttons)} buttons, "
            f"{len(inputs)} inputs, {len(forms)} forms, {len(links)} links ({total_elements} interactive elements)."
        )
        try:
            raw_test_batches = []
            for idx, batch_ctx in enumerate(batches, 1):
                batch_focus = batch_ctx.get("focus_area", "General Functional Suite")
                logger.info(f"Executing AI Generation Batch {idx}/{len(batches)}: '{batch_focus}' via {provider.get_name()}...")
                try:
                    batch_res = provider.generate_test_cases(batch_ctx)
                    logger.info(f"Batch {idx} returned {len(batch_res)} raw AI candidates from {provider.get_name()}.")
                    raw_test_batches.extend(batch_res)
                except Exception as b_err:
                    logger.warning(f"Batch {idx} ({batch_focus}) encountered error with {provider.get_name()}: {b_err}")
                    # If this is a quota or auth error, re-raise to trigger provider fallback
                    err_str = str(b_err).lower()
                    if "429" in err_str or "quota" in err_str or "rate" in err_str or "credit" in err_str:
                        raise

            # Pydantic schema validation
            validated = []
            rejected_count = 0
            for item in raw_test_batches:
                try:
                    tc_model = GeneratedTestCase(**item)
                    validated.append(tc_model.model_dump())
                except Exception as val_err:
                    rejected_count += 1
                    logger.warning(f"Skipping schema-invalid test from AI: {val_err} (name: {item.get('name')})")

            logger.info(
                f"AI Generation Stage Completed with {provider.get_name()}: {len(raw_test_batches)} raw candidates generated across "
                f"{len(batches)} batches, {len(validated)} schema-validated, {rejected_count} schema-rejected."
            )

            if validated:
                return validated, provider.get_name(), True
            else:
                logger.warning(f"AI provider {provider.get_name()} returned 0 valid test cases, attempting fallback if available.")

        except Exception as e:
            last_error = e
            logger.warning(f"AI provider {provider.get_name()} failed during test generation: {e}. Attempting next provider...")
            continue

    if last_error:
        raise RuntimeError(f"All AI test generation providers failed. Last error: {str(last_error)}")
    return [], "", False
